const file = path.join(__dirname, '..', 'cloud', 'functions', 'resetAndImport', 'data.js');
const lines = fs.readFileSync(file, 'utf8').split(/\r?\n/);

const startIdx = lines.findIndex((l) => /^\s*name: '公式',\s*$/.test(l));
if (startIdx < 0) throw new Error('找不到「公式」学习路径起点');

let textbook = '';
let annotated = 0;
let skipped = 0;
let pending = -1; // 待插入 grade 的行号（word 所在行之后的锚点）
let pendingWord = '';
let pendingKey = '';

// 先做一次「待标注全集」校验
const remaining = new Set(Object.keys(GRADE));

for (let i = startIdx; i < lines.length; i += 1) {
  const line = lines[i];

  const tb = /^\s*name: '(小学公式专题|初中公式专题)',\s*$/.exec(line);
  if (tb) textbook = tb[1];

  if (pending >= 0) {
    // 只锚定 type: 'formula'（已校验 74 条全都有），避免误命中章节/册次的 order 行
    if (/^\s*type: 'formula',\s*$/.test(line)) {
      const indent = /^(\s*)/.exec(line)[1];
      const grade = GRADE[pendingKey];
      if (grade === undefined) throw new Error(`缺少年级标注：${pendingKey}`);
      lines.splice(i + 1, 0, `${indent}grade: ${grade},`);
      remaining.delete(pendingKey);
      annotated += 1;
      pending = -1;
      i += 1; // 跳过刚插入的行
      continue;
    }
  }

  const w = /^\s*word: '(.+)',\s*$/.exec(line);
  if (w) {
    pendingWord = w[1];
    pendingKey = `${textbook}|${pendingWord}`;
    // 已标注过则跳过（幂等）
    const already = lines.slice(i, i + 8).some((l) => /^\s*grade: \d+,\s*$/.test(l));
    pending = already ? -1 : i;
    if (already) {
      remaining.delete(pendingKey);
      skipped += 1;
    }
  }
}

if (remaining.size > 0) {
  throw new Error(`以下条目未匹配到（数据里可能已改名）：\n${[...remaining].join('\n')}`);
}

fs.writeFileSync(file, lines.join('\n'), 'utf8');
console.log(`完成：新增 ${annotated} 条，跳过（已有 grade）${skipped} 条`);
